//! Cold-storage archiving for persistent outbox events.
//!
//! Old persistent events are swept out of postgres one settled span at a
//! time: the events of the span are written to object storage as JSONL
//! files (see [`EventArchiveStorage`]), recorded in the
//! `persistent_outbox_archive_chunks` manifest table, and deleted from the
//! live events table — atomically per file. Reads are unaffected from the
//! consumer's point of view: a listener resuming from a cursor below the
//! archive watermark is transparently served from object storage first,
//! then crosses over to postgres mid-stream.
//!
//! Which spans are eligible for archiving is decided by an
//! [`ArchiveBoundaryProvider`]: anything that can certify contiguous
//! history as final, at a stream position. The default
//! [`DailyRetentionBoundary`] certifies history purely by age;
//! deployments with an end-of-day process can instead certify from their
//! own marker event on the stream (e.g. an `EndOfDaySettled` whose
//! sequence closes the span), keeping late settlement-processing events
//! inside the span they belong to.
//!
//! Object storage itself is not implemented here — consumers plug in their
//! backend (GCS, S3, ...) by implementing [`EventArchiveStorage`]. An
//! [`InMemoryArchiveStorage`] is provided for tests.
//!
//! # Operator notes
//!
//! **Corrupt chunk file.** A mid-file line that does not parse aborts the
//! backfill that hit it and retries every few seconds — symptom:
//! `obix.persistent_cache.archive_backfill_failed` spans carrying a Codec
//! error, and consumers below the watermark making no progress. The chunk
//! path (in the error and in the manifest) is the format of record:
//! repair or replace the object at that path (it can be regenerated by
//! re-exporting the span — deleting the manifest row lets the archiver
//! sweep it again). A torn *final* line (truncated write) does not wedge:
//! it degrades to placeholder deliveries for the chunk's tail, traced via
//! `obix.archive.line_torn`.
//!
//! **Missing archive reader.** Every pod that might serve pre-watermark
//! reads must be configured with the same [`ArchiveConfig`]. A pod
//! without it degrades to placeholder deliveries below the watermark
//! (`obix.persistent_cache.archive_reader_missing`, warn) — loud but
//! degraded.

